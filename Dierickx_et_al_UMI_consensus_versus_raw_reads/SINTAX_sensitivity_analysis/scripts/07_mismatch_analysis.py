#!/usr/bin/env python3
"""Audit CURRENT ITS-standardized SINTAX D1-consensus vs D3-read SH conflicts.

Preserves unfiltered outputs and additionally reports sensitivity after excluding
all *mismatched* pairs involving the specified putatively chimeric SH.
Matched and unmatched reads are not removed. Filtered mismatch rates use an
adjusted eligible-read denominator that excludes the removed conflict rows.

Python standard library only. Uses existing paired SINTAX read-level outputs, no
new classification or taxonomic inference.

Run:
    python3 scripts/07_mismatch_analysis.py

For unexpected SH column names:
    python3 scripts/07_mismatch_analysis.py --show-columns
    python3 scripts/07_mismatch_analysis.py \
        --d1-column 'exact D1 SH column' --d3-column 'exact D3 SH column'

Optional name map: --taxonomy-tsv file.tsv (SH_ID and Taxon columns).
"""
import argparse
import csv
import gzip
import os
import re
from collections import Counter, defaultdict
from pathlib import Path

DEFAULT_REVIEW = Path(os.environ['REVIEW_DIR']).resolve() if os.environ.get('REVIEW_DIR') else None
SH_RE = re.compile(r'(?<![A-Za-z0-9])SH\d{7}\.[A-Za-z0-9]+(?![A-Za-z0-9])', re.I)
HY_1, HY_2 = 'SH0994900.10FU', 'SH0889625.10FU'
HY_PAIR = frozenset((HY_1, HY_2))
CHIMERIC_SH = "SH0074422.10FU"  # User-reported, UNITE-acknowledged chimeric reference
OUTCOME_VALUES = {'matched', 'unmatched', 'mismatched', 'excluded_d1_low_confidence'}

def fail(message):
    raise SystemExit('ERROR: ' + message)

def format_column(s):
    return re.sub(r'[^a-z0-9]+', '_', s.lower()).strip('_')

def choose_sh_column(header, kind, specified):
    if specified:
        if specified not in header:
            fail(f'--{kind}-column={specified!r} is absent. Columns: {header}')
        return specified

    norm = {c: format_column(c) for c in header}
    # Unambiguous high-priority names from common paired-SINTAX workflows.
    if kind == 'd1':
        names = ['D1_SH_080', 'D1_sintax_SH', 'sintax_D1_SH', 'D1_SH',
                 'consensus_SH_080', 'consensus_sintax_SH', 'consensus_SH',
                 'D1_SH_code', 'SH_D1', 'D1_species_SH', 'D1_species']
        subject = ('d1', 'consensus', 'umi_consensus')
    else:
        names = ['D3_SH_080', 'D3_sintax_SH', 'sintax_D3_SH', 'D3_SH',
                 'raw_SH_080', 'raw_sintax_SH', 'raw_SH', 'read_SH_080',
                 'read_sintax_SH', 'read_SH', 'D3_SH_code', 'SH_D3', 'D3_species_SH']
        subject = ('d3', 'raw', 'read', 'input')
    for expected in names:
        for col in header:
            if format_column(col) == format_column(expected):
                return col

    # Score candidates, but never silently choose among ambiguous best matches.
    scored = []
    for col, n in norm.items():
        terms = set(n.split('_'))
        has_subject = any(s in terms or s in n for s in subject)
        if not has_subject or any(tok in terms for tok in ('015', 'original', 'shmatching')):
            continue
        if not any(tok in terms for tok in ('sh', 'species', 'taxon', 'taxonomy', 'assignment', 'sintax')):
            continue
        score = (5 if 'sh' in terms else 0) + (3 if 'sintax' in terms else 0) + (2 if '080' in terms or '80' in terms else 0)
        if any(tok in terms for tok in ('confidence', 'bootstrap', 'score', 'quality')):
            score -= 10
        if score > 0:
            scored.append((score, col))
    if scored:
        best_score = max(s for s, _ in scored)
        best = [col for score, col in scored if score == best_score]
        if len(best) == 1:
            return best[0]
    fail(f'Could not uniquely identify {kind.upper()} SINTAX SH column. '\
         f'Found: {header}\nUse --{kind}-column "column name" after --show-columns.')

def get_id(s):
    value = s.strip()
    if not value or value.lower() in ('na', 'nan', 'none', 'unclassified', 'unassigned'):
        return ''
    hit = SH_RE.search(value)
    return hit.group(0).upper() if hit else ''

def load_cohort(review, cohort_path):
    if cohort_path is None or not cohort_path.is_file():
        fail('Pass --cohort-file generated by scripts/06_classification_success.py.')
    cohort = [line.strip() for line in cohort_path.read_text().splitlines() if line.strip()]
    if len(cohort) not in (90, 97) or len(set(cohort)) != len(cohort):
        fail(f'Expected 90 or 97 distinct current barcodes, observed {len(cohort)}.')
    return sorted(cohort)

def load_labels(p):
    labels = {}
    if p is None:
        return labels
    with p.open(newline='', encoding='utf-8-sig') as h:
        dialect = csv.excel_tab if p.suffix.lower() == '.tsv' else csv.excel
        rdr = csv.DictReader(h, dialect=dialect)
        if not {'SH_ID', 'Taxon'}.issubset(rdr.fieldnames or []):
            fail('--taxonomy-tsv requires columns SH_ID and Taxon.')
        for row in rdr:
            sh = get_id(row['SH_ID'])
            if sh:
                labels[sh] = row['Taxon'].strip()
    return labels

def write_tsv(path, rows, columns):
    with path.open('w', newline='', encoding='utf-8') as h:
        writer = csv.DictWriter(h, fieldnames=columns, delimiter='\t', extrasaction='ignore')
        writer.writeheader()
        writer.writerows(rows)

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--review-dir', type=Path, default=DEFAULT_REVIEW, required=DEFAULT_REVIEW is None)
    ap.add_argument('--cohort-file', type=Path, required=True, help='Current all97.txt or A1filtered90.txt from script 15')
    ap.add_argument('--pair-dir', type=Path, help='Directory containing <barcode>.paired.tsv.gz files')
    ap.add_argument('--out-dir', type=Path)
    ap.add_argument('--d1-column', help='Exact column containing consensus SINTAX SH identifier')
    ap.add_argument('--d3-column', help='Exact column containing raw-read SINTAX SH identifier')
    ap.add_argument('--taxonomy-tsv', type=Path, help='Optional TSV with SH_ID and Taxon columns')
    ap.add_argument('--show-columns', action='store_true', help='Print first paired file header and exit')
    ap.add_argument('--exclude-conflict-sh', default=CHIMERIC_SH,
                    help='Exclude mismatched pairs involving this SH from the sensitivity outputs (default: SH0074422.10FU). The original unfiltered outputs are retained.')
    args = ap.parse_args()

    excluded_sh = get_id(args.exclude_conflict_sh)
    if not excluded_sh:
        fail('--exclude-conflict-sh must be an SH identifier such as SH0074422.10FU')
    review = args.review_dir.resolve()
    pair_dir = args.pair_dir or review / 'SINTAX_equal_ITS_v1' / 'paired_by_barcode'
    cohort = load_cohort(review, args.cohort_file)
    out_dir = args.out_dir or review / 'SINTAX_equal_ITS_v1' / 'analysis' / 'appendixC_current' / f'chimera_{len(cohort)}'
    filenames = [pair_dir / (bc + '.paired.tsv.gz') for bc in cohort]
    missing = [str(path) for path in filenames if not path.is_file()]
    if missing:
        fail(f'Missing {len(missing)} paired files; first missing: {missing[:8]}')

    with gzip.open(filenames[0], 'rt', newline='', encoding='utf-8-sig') as h:
        header = next(csv.reader(h, delimiter='\t'))
    print('Paired SINTAX columns:')
    for col in header:
        print('  ' + col)
    if args.show_columns:
        return
    if 'annotation_080' not in header:
        fail('Expected annotation_080 in paired files. Existing analysis uses this field.')
    d1_col = choose_sh_column(header, 'd1', args.d1_column)
    d3_col = choose_sh_column(header, 'd3', args.d3_column)
    if d1_col == d3_col:
        fail('D1 and D3 SH columns resolved to the same column.')
    print(f'\nUsing D1 consensus SH: {d1_col}; D3 raw-read SH: {d3_col}')
    print(f'CURRENT ITS-standardized cohort: {len(cohort)} barcodes; SINTAX bootstrap >=0.80')

    # These names are explicitly associated with SHs in the original manuscript.
    # They are identification annotations, not an assertion of ground-truth species.
    labels = {
        HY_1: 'Hypholoma fasciculare [original SH annotation]',
        HY_2: 'Hypholoma fasciculare [original SH annotation]',
        'SH0861374.10FU': 'Amylosporus guaraniticus [original SH annotation]',
        'SH0861376.10FU': 'Amylosporus guaraniticus [original SH annotation]',
        'SH0913328.10FU': 'Hypoxylon macrocarpum [original SH annotation]',
        'SH0913330.10FU': 'Hypoxylon macrocarpum [original SH annotation]',
    }
    labels.update(load_labels(args.taxonomy_tsv))
    # Counts are read-weighted, not consensus-weighted.
    outcome_counts = Counter()
    pair_counts = Counter()
    pair_barcodes = defaultdict(set)
    direction_barcodes = defaultdict(set)
    mismatch_by_barcode = Counter()
    excluded_by_barcode = Counter()
    excluded_by_d1 = Counter()
    excluded_by_d3 = Counter()
    eligible_by_barcode = Counter()
    total_by_barcode = Counter()
    eligible_by_d1 = Counter()
    matched_by_d1 = Counter()
    unmatched_by_d1 = Counter()
    mismatched_by_d1 = Counter()
    eligible_by_raw = Counter()  # only when D3 was confidently SH-assigned
    mismatched_by_raw = Counter()
    consensus_barcodes = defaultdict(set)
    n_bad_sh = 0
    errors = []
    total = 0

    for bc, path in zip(cohort, filenames):
        with gzip.open(path, 'rt', newline='', encoding='utf-8-sig') as h:
            reader = csv.reader(h, delimiter='\t')
            current_header = next(reader)
            if current_header != header:
                fail(f'Column names/order differ in {path}.')
            idx = {c: i for i, c in enumerate(header)}
            ai = idx['annotation_080']
            i1, i3 = idx[d1_col], idx[d3_col]
            bi = idx.get('Barcode')
            for line_no, row in enumerate(reader, start=2):
                if not row or (len(row) == 1 and not row[0]):
                    continue
                if len(row) != len(header):
                    fail(f'Malformed record in {path}:{line_no}: got {len(row)} columns, expected {len(header)}')
                if bi is not None and row[bi] != bc:
                    fail(f'Barcode field disagrees with file name at {path}:{line_no}: {row[bi]}')
                outcome = row[ai].strip().lower()
                if outcome not in OUTCOME_VALUES:
                    fail(f'Unexpected annotation_080={outcome!r} in {path}:{line_no}')
                total += 1
                total_by_barcode[bc] += 1
                outcome_counts[outcome] += 1
                if outcome == 'excluded_d1_low_confidence':
                    continue
                d1 = get_id(row[i1])
                if not d1:
                    n_bad_sh += 1
                    if len(errors) < 5:
                        errors.append(f'{path.name}:{line_no} D1: {row[i1]!r} ({outcome})')
                    continue
                eligible_by_d1[d1] += 1
                eligible_by_barcode[bc] += 1
                consensus_barcodes[d1].add(bc)
                if outcome == 'unmatched':
                    unmatched_by_d1[d1] += 1
                    continue
                d3 = get_id(row[i3])
                if not d3:
                    n_bad_sh += 1
                    if len(errors) < 5:
                        errors.append(f'{path.name}:{line_no} D3: {row[i3]!r} ({outcome})')
                    continue
                eligible_by_raw[d3] += 1
                if outcome == 'matched':
                    if d1 != d3:
                        fail(f'Matched outcome but different SH codes in {path}:{line_no}: {d1} -> {d3}')
                    matched_by_d1[d1] += 1
                else:
                    if d1 == d3:
                        fail(f'Mismatched outcome but identical SH codes in {path}:{line_no}: {d1}')
                    key = (d1, d3)
                    pair_counts[key] += 1
                    pair_barcodes[frozenset(key)].add(bc)
                    direction_barcodes[key].add(bc)
                    mismatched_by_d1[d1] += 1
                    mismatched_by_raw[d3] += 1
                    mismatch_by_barcode[bc] += 1
                    if excluded_sh in (d1, d3):
                        excluded_by_barcode[bc] += 1
                        excluded_by_d1[d1] += 1
                        excluded_by_d3[d3] += 1
        print(f'  {bc}: {total_by_barcode[bc]:,} rows; {mismatch_by_barcode[bc]:,} mismatches', flush=True)

    if n_bad_sh:
        fail(f'{n_bad_sh:,} eligible read assignments were missing SH identifiers or malformed. '\
             f'First cases: {errors}. Check --d1-column and --d3-column.')
    if total != sum(outcome_counts.values()):
        fail('Internal error: tally mismatch.')
    if sum(pair_counts.values()) != outcome_counts['mismatched']:
        fail('Mismatch pairs do not account for all rows labelled mismatched.')
    if sum(eligible_by_d1.values()) != total - outcome_counts['excluded_d1_low_confidence']:
        fail('Eligible reads are not completely accounted for by D1 SHs.')
    if sum(eligible_by_raw.values()) != outcome_counts['matched'] + outcome_counts['mismatched']:
        fail('Reads with D3 SH assignments do not reconcile to outcome totals.')

    audit_path = review / 'SINTAX_equal_ITS_v1' / 'standardization_audit.tsv'
    with audit_path.open(newline='') as handle:
        data = list(csv.DictReader(handle, delimiter='\t'))
    expected_by_bc = {r['barcode']: int(r['input_reads']) for r in data if r['dataset'] == 'D3'}
    if set(cohort) - set(expected_by_bc):
        fail('The standardization audit lacks D3 denominators for some cohort barcodes')
    expected = sum(expected_by_bc[bc] for bc in cohort)
    if total != expected:
        fail(f'Paired files contain {total:,} D3 reads, but current D3 audit has {expected:,}.')
    print(f'PASS: current paired D3 rows equal original-input denominators ({expected:,}).')

    # Match the independent, threshold-specific paired summary generated by
    # script 03. This ensures all cohorts use the same annotation definition.
    sums = review / 'SINTAX_equal_ITS_v1' / 'summary_by_barcode'
    expected_outcomes = Counter()
    for bc in cohort:
        with (sums / f'{bc}.summary.tsv').open(newline='') as handle:
            rr = [row for row in csv.DictReader(handle, delimiter='\t')
                  if abs(float(row['cutoff']) - 0.80) < 1e-9]
        if len(rr) != 1:
            fail(f'Missing/duplicate current 0.80 summary for {bc}')
        for label, name in [('matched', 'matched'), ('unmatched', 'unmatched'),
                            ('mismatched', 'mismatched'),
                            ('excluded_d1_low_confidence', 'excluded_D1_low_confidence')]:
            expected_outcomes[label] += int(rr[0][name])
    if any(outcome_counts[k] != expected_outcomes[k] for k in OUTCOME_VALUES):
        fail(f'Current per-barcode summary and direct chimera-audit counts disagree: '
             f'{outcome_counts} vs {expected_outcomes}')
    print('PASS: read-level outcomes agree with independently generated paired summaries.')

    out_dir.mkdir(parents=True, exist_ok=True)
    n_mismatches = outcome_counts['mismatched']
    sorted_pairs = sorted(pair_counts.items(), key=lambda kv: (-kv[1], kv[0]))
    direction_rows = []
    cumulative = 0
    for rank, ((d1, d3), n) in enumerate(sorted_pairs, 1):
        cumulative += n
        direction_rows.append(dict(
            Rank=rank, D1_consensus_SH=d1, D3_raw_read_SH=d3,
            D1_taxon=labels.get(d1, ''), D3_taxon=labels.get(d3, ''),
            Mismatched_reads=n,
            Pct_all_SINTAX_mismatches=round(100*n/n_mismatches, 6),
            Cumulative_pct=round(100*cumulative/n_mismatches, 6),
            Barcodes_with_pair=len(direction_barcodes[(d1, d3)]),
            Pct_D1_eligible_reads=round(100*n/eligible_by_d1[d1], 6),
            Hypholoma_fasciculare_reference_pair=('yes' if frozenset((d1, d3)) == HY_PAIR else 'no')
        ))

    combined = Counter()
    for (d1, d3), n in pair_counts.items():
        combined[tuple(sorted((d1, d3)))] += n
    combined_rows = []
    cumulative = 0
    for rank, ((a, b), n) in enumerate(sorted(combined.items(), key=lambda kv: (-kv[1], kv[0])), 1):
        cumulative += n
        combined_rows.append(dict(
            Rank=rank, SH_A=a, SH_B=b, SH_A_taxon=labels.get(a, ''), SH_B_taxon=labels.get(b, ''),
            Total_mismatched_reads=n, SH_A_to_SH_B=pair_counts[(a, b)],
            SH_B_to_SH_A=pair_counts[(b, a)],
            Pct_all_SINTAX_mismatches=round(100*n/n_mismatches, 6),
            Cumulative_pct=round(100*cumulative/n_mismatches, 6),
            Barcodes_with_pair=len(pair_barcodes[frozenset((a, b))]),
            Hypholoma_fasciculare_reference_pair=('yes' if frozenset((a, b)) == HY_PAIR else 'no')
        ))

    by_consensus = []
    for sh, eligible in sorted(eligible_by_d1.items(), key=lambda kv: (-mismatched_by_d1[kv[0]], kv[0])):
        mismatches = mismatched_by_d1[sh]
        by_consensus.append(dict(
            D1_consensus_SH=sh, D1_taxon=labels.get(sh, ''), Eligible_D3_reads=eligible,
            Matched_D3_reads=matched_by_d1[sh], Unmatched_D3_reads=unmatched_by_d1[sh],
            Mismatched_D3_reads=mismatches, Mismatch_rate_pct=round(100*mismatches/eligible, 6),
            Pct_all_SINTAX_mismatches=round(100*mismatches/n_mismatches, 6),
            Barcodes_with_D1_SH=len(consensus_barcodes[sh]),
            Distinct_alternative_D3_SH=len({d3 for (d1, d3) in pair_counts if d1 == sh})
        ))

    by_raw = []
    for sh, assigned in sorted(eligible_by_raw.items(), key=lambda kv: (-mismatched_by_raw[kv[0]], kv[0])):
        mismatches = mismatched_by_raw[sh]
        by_raw.append(dict(
            D3_raw_read_SH=sh, D3_taxon=labels.get(sh, ''), Assigned_D3_reads=assigned,
            Mismatched_D3_reads=mismatches, Mismatch_rate_pct=round(100*mismatches/assigned, 6),
            Pct_all_SINTAX_mismatches=round(100*mismatches/n_mismatches, 6)
        ))

    per_barcode = []
    for bc in cohort:
        per_barcode.append(dict(Barcode=bc, All_D3_reads=total_by_barcode[bc],
                                Mismatched_reads=mismatch_by_barcode[bc],
                                Pct_all_D3_reads=round(100*mismatch_by_barcode[bc]/total_by_barcode[bc], 6)))
    per_barcode.sort(key=lambda row: (-row['Mismatched_reads'], row['Barcode']))

    hy_related_rows = [r for r in direction_rows if r['D1_consensus_SH'] in (HY_1, HY_2) or r['D3_raw_read_SH'] in (HY_1, HY_2)]

    outputs = {
        'SINTAX080_conflicting_SH_pairs_directional.tsv': direction_rows,
        'SINTAX080_Hypholoma_SH_involving_pairs.tsv': hy_related_rows,
        'SINTAX080_conflicting_SH_pairs_bidirectional.tsv': combined_rows,
        'SINTAX080_mismatches_by_D1_consensus_SH.tsv': by_consensus,
        'SINTAX080_mismatches_by_D3_raw_SH.tsv': by_raw,
        'SINTAX080_mismatches_by_barcode.tsv': per_barcode,
    }
    for filename, rows in outputs.items():
        columns = list(rows[0].keys()) if rows else {'SINTAX080_conflicting_SH_pairs_directional.tsv': ['D1_consensus_SH', 'D3_raw_read_SH'],
            'SINTAX080_conflicting_SH_pairs_bidirectional.tsv': ['SH_A', 'SH_B'],
            'SINTAX080_Hypholoma_SH_involving_pairs.tsv': ['D1_consensus_SH', 'D3_raw_read_SH'],
            'SINTAX080_mismatches_by_D1_consensus_SH.tsv': ['D1_consensus_SH'],
            'SINTAX080_mismatches_by_D3_raw_SH.tsv': ['D3_raw_read_SH'],
            'SINTAX080_mismatches_by_barcode.tsv': ['Barcode']}[filename]
        write_tsv(out_dir / filename, rows, columns)

    audit = [{'Metric': 'Barcodes', 'Value': len(cohort)},
             {'Metric': 'Confident on both D1 and D3', 'Value': outcome_counts['matched'] + outcome_counts['mismatched']},
             {'Metric': 'Observed conflict percent of both-confident pairs',
              'Value': round(100*n_mismatches/(outcome_counts['matched']+n_mismatches), 6)},
             {'Metric': 'Total paired D3 reads', 'Value': total},
             {'Metric': 'D1 low-confidence excluded', 'Value': outcome_counts['excluded_d1_low_confidence']},
             {'Metric': 'SINTAX D1-eligible D3 reads', 'Value': sum(eligible_by_d1.values())},
             {'Metric': 'Matched', 'Value': outcome_counts['matched']},
             {'Metric': 'Unmatched', 'Value': outcome_counts['unmatched']},
             {'Metric': 'Mismatched', 'Value': n_mismatches},
             {'Metric': 'Mismatched pct among eligible', 'Value': round(100*n_mismatches/sum(eligible_by_d1.values()), 6)},
             {'Metric': 'Distinct directed SH pairs', 'Value': len(pair_counts)},
             {'Metric': 'Distinct undirected SH pairs', 'Value': len(combined)}]
    hy_total = combined.get(tuple(sorted((HY_1, HY_2))), 0)
    hy_involving = sum(n for (d1, d3), n in pair_counts.items() if d1 in (HY_1, HY_2) or d3 in (HY_1, HY_2))
    audit.extend([{'Metric': 'Hypholoma reference SH pair mismatched reads', 'Value': hy_total},
                  {'Metric': 'Hypholoma pair percent of all SINTAX mismatches',
                   'Value': round(100*hy_total/n_mismatches, 6)},
                  {'Metric': 'Mismatches involving either Hypholoma-associated SH', 'Value': hy_involving},
                  {'Metric': 'Percent involving either Hypholoma-associated SH', 'Value': round(100*hy_involving/n_mismatches, 6)}])
    write_tsv(out_dir / 'SINTAX080_confusion_audit.tsv', audit, ['Metric', 'Value'])

    print('\n=== SINTAX 0.80, CURRENT ITS-standardized cohort ===')
    for r in audit:
        print(f"  {r['Metric']}: {r['Value']}")
    print('\nTop 15 directional conflicting SH pairs:')
    print('Rank\tD1 consensus SH\tD3 raw SH\tN\t% mismatches\tBarcodes')
    for r in direction_rows[:15]:
        print(f"{r['Rank']}\t{r['D1_consensus_SH']}\t{r['D3_raw_read_SH']}\t{r['Mismatched_reads']:,}\t{r['Pct_all_SINTAX_mismatches']:.2f}\t{r['Barcodes_with_pair']}")
    print('\nTop 15 D1 SHs by mismatched read count:')
    print('D1 consensus SH\tEligible reads\tMismatched reads\tMismatch rate %')
    for r in by_consensus[:15]:
        print(f"{r['D1_consensus_SH']}\t{r['Eligible_D3_reads']:,}\t{r['Mismatched_D3_reads']:,}\t{r['Mismatch_rate_pct']:.2f}")
    print('\nOutput files:')
    for name in list(outputs) + ['SINTAX080_confusion_audit.tsv']:
        print('  ' + str(out_dir / name))
    print('\nInterpretation: read-weighted SH disagreement within SINTAX, not verified taxonomic errors.')

    # Targeted sensitivity analysis: ignore ONLY conflicting pairs
    # Excluded conflicts are removed from numerator AND denominator of
    excluded_pairs = Counter({key: n for key, n in pair_counts.items()
                              if excluded_sh in key})
    kept_pairs = Counter({key: n for key, n in pair_counts.items()
                          if excluded_sh not in key})
    n_excluded = sum(excluded_pairs.values())
    n_kept = sum(kept_pairs.values())
    eligible_original = sum(eligible_by_d1.values())
    eligible_adjusted = eligible_original - n_excluded

    if n_excluded != sum(excluded_by_barcode.values()):
        fail('Excluded conflicts do not reconcile across barcodes.')
    if n_excluded != sum(excluded_by_d1.values()):
        fail('Excluded conflicts do not reconcile across D1 SHs.')
    if n_excluded != sum(excluded_by_d3.values()):
        fail('Excluded conflicts do not reconcile across D3 SHs.')
    if n_mismatches != n_excluded + n_kept:
        fail('Original mismatches do not reconcile to excluded + retained.')
    if eligible_adjusted != outcome_counts['matched'] + outcome_counts['unmatched'] + n_kept:
        fail('Adjusted eligible read count does not reconcile to retained outcomes.')

    excluded_dir = out_dir / ('exclude_' + excluded_sh)
    excluded_dir.mkdir(parents=True, exist_ok=True)

    filtered_direction = []
    running = 0
    for rank, ((d1, d3), n) in enumerate(sorted(kept_pairs.items(),
            key=lambda kv: (-kv[1], kv[0])), 1):
        running += n
        adjusted_sh_eligible = eligible_by_d1[d1] - excluded_by_d1[d1]
        filtered_direction.append(dict(
            Rank=rank, D1_consensus_SH=d1, D3_raw_read_SH=d3,
            D1_taxon=labels.get(d1, ''), D3_taxon=labels.get(d3, ''),
            Mismatched_reads=n,
            Pct_nonchimeric_mismatches=round(100*n/n_kept, 6) if n_kept else 0,
            Cumulative_pct=round(100*running/n_kept, 6) if n_kept else 0,
            Barcodes_with_pair=len(direction_barcodes[(d1, d3)]),
            Pct_adjusted_D1_eligible_reads=(round(100*n/adjusted_sh_eligible, 6)
                                            if adjusted_sh_eligible else 0)))

    undirected_kept = Counter()
    for (d1, d3), n in kept_pairs.items():
        undirected_kept[tuple(sorted((d1, d3)))] += n
    filtered_bidirectional = []
    running = 0
    for rank, ((a, b), n) in enumerate(sorted(undirected_kept.items(),
            key=lambda kv: (-kv[1], kv[0])), 1):
        running += n
        filtered_bidirectional.append(dict(
            Rank=rank, SH_A=a, SH_B=b,
            SH_A_taxon=labels.get(a, ''), SH_B_taxon=labels.get(b, ''),
            Total_mismatched_reads=n,
            SH_A_to_SH_B=kept_pairs[(a, b)], SH_B_to_SH_A=kept_pairs[(b, a)],
            Pct_nonchimeric_mismatches=round(100*n/n_kept, 6) if n_kept else 0,
            Cumulative_pct=round(100*running/n_kept, 6) if n_kept else 0,
            Barcodes_with_pair=len(pair_barcodes[frozenset((a, b))])))

    filtered_by_d1 = []
    for d1, eligible in eligible_by_d1.items():
        removed = excluded_by_d1[d1]
        adjusted = eligible - removed
        keep = mismatched_by_d1[d1] - removed
        if adjusted <= 0:
            continue
        filtered_by_d1.append(dict(
            D1_consensus_SH=d1, D1_taxon=labels.get(d1, ''),
            Original_D1_eligible_reads=eligible, Excluded_chimeric_conflicts=removed,
            Adjusted_D1_eligible_reads=adjusted,
            Matched_D3_reads=matched_by_d1[d1],
            Unmatched_D3_reads=unmatched_by_d1[d1],
            Nonchimeric_mismatched_D3_reads=keep,
            Mismatch_rate_pct=round(100*keep/adjusted, 6),
            Pct_nonchimeric_mismatches=round(100*keep/n_kept, 6) if n_kept else 0,
            Barcodes_with_D1_SH=len(consensus_barcodes[d1]),
            Distinct_alternative_D3_SH=len({d3 for a, d3 in kept_pairs if a == d1})))
    filtered_by_d1.sort(key=lambda row: (-row['Nonchimeric_mismatched_D3_reads'],
                                         row['D1_consensus_SH']))

    filtered_by_raw = []
    for d3, assigned in eligible_by_raw.items():
        removed = excluded_by_d3[d3]
        adjusted = assigned - removed
        keep = mismatched_by_raw[d3] - removed
        if adjusted <= 0:
            continue
        filtered_by_raw.append(dict(
            D3_raw_read_SH=d3, D3_taxon=labels.get(d3, ''),
            Original_D3_assigned_reads=assigned,
            Excluded_chimeric_conflicts=removed,
            Adjusted_D3_assigned_reads=adjusted,
            Nonchimeric_mismatched_D3_reads=keep,
            Mismatch_rate_pct=round(100*keep/adjusted, 6),
            Pct_nonchimeric_mismatches=round(100*keep/n_kept, 6) if n_kept else 0))
    filtered_by_raw.sort(key=lambda row: (-row['Nonchimeric_mismatched_D3_reads'],
                                          row['D3_raw_read_SH']))

    filtered_by_barcode = []
    for bc in cohort:
        n = mismatch_by_barcode[bc] - excluded_by_barcode[bc]
        eligible = eligible_by_barcode[bc] - excluded_by_barcode[bc]
        filtered_by_barcode.append(dict(
            Barcode=bc, All_D3_reads=total_by_barcode[bc],
            Original_D1_eligible_reads=eligible_by_barcode[bc],
            Excluded_chimeric_conflicts=excluded_by_barcode[bc],
            Adjusted_D1_eligible_reads=eligible,
            Nonchimeric_mismatched_reads=n,
            Mismatch_rate_pct=round(100*n/eligible, 6) if eligible else 0))
    filtered_by_barcode.sort(key=lambda row: (-row['Nonchimeric_mismatched_reads'],
                                              row['Barcode']))

    filtered_exclusions = []
    for (d1, d3), n in sorted(excluded_pairs.items(), key=lambda kv: (-kv[1], kv[0])):
        filtered_exclusions.append(dict(
            D1_consensus_SH=d1, D3_raw_read_SH=d3, Excluded_mismatched_reads=n,
            Pct_all_original_mismatches=round(100*n/n_mismatches, 6),
            Barcodes_with_pair=len(direction_barcodes[(d1, d3)])))

    filtered_audit = [
        {'Metric': 'Current barcodes', 'Value': len(cohort)},
        {'Metric': 'Excluded reference SH', 'Value': excluded_sh},
        {'Metric': 'Exclusion rule', 'Value': 'mismatched D1/D3 pair containing excluded SH'},
        {'Metric': 'All paired D3 reads', 'Value': total},
        {'Metric': 'Original D1 eligible reads', 'Value': eligible_original},
        {'Metric': 'Original SINTAX mismatches', 'Value': n_mismatches},
        {'Metric': 'Excluded chimeric-reference conflicts', 'Value': n_excluded},
        {'Metric': 'Percent of original mismatches excluded',
         'Value': round(100*n_excluded/n_mismatches, 6) if n_mismatches else 0},
        {'Metric': 'Adjusted eligible D3 reads', 'Value': eligible_adjusted},
        {'Metric': 'Matched reads retained', 'Value': outcome_counts['matched']},
        {'Metric': 'Unmatched reads retained', 'Value': outcome_counts['unmatched']},
        {'Metric': 'Nonchimeric mismatches remaining', 'Value': n_kept},
        {'Metric': 'Adjusted mismatch rate percent',
         'Value': round(100*n_kept/eligible_adjusted, 6) if eligible_adjusted else 0},
        {'Metric': 'Nonchimeric directed SH pairs', 'Value': len(kept_pairs)},
        {'Metric': 'Nonchimeric undirected SH pairs', 'Value': len(undirected_kept)},
        {'Metric': '01P1 excluded mismatches', 'Value': excluded_by_barcode['01P1']},
        {'Metric': '01P1 nonchimeric mismatches',
         'Value': mismatch_by_barcode['01P1'] - excluded_by_barcode['01P1']},
    ]

    filtered_outputs = {
        'SINTAX080_nonchimeric_conflicting_SH_pairs_directional.tsv':
            (filtered_direction, ['Rank', 'D1_consensus_SH', 'D3_raw_read_SH',
             'D1_taxon', 'D3_taxon', 'Mismatched_reads',
             'Pct_nonchimeric_mismatches', 'Cumulative_pct',
             'Barcodes_with_pair', 'Pct_adjusted_D1_eligible_reads']),
        'SINTAX080_nonchimeric_conflicting_SH_pairs_bidirectional.tsv':
            (filtered_bidirectional, ['Rank', 'SH_A', 'SH_B', 'SH_A_taxon',
             'SH_B_taxon', 'Total_mismatched_reads', 'SH_A_to_SH_B',
             'SH_B_to_SH_A', 'Pct_nonchimeric_mismatches', 'Cumulative_pct',
             'Barcodes_with_pair']),
        'SINTAX080_nonchimeric_mismatches_by_D1_consensus_SH.tsv':
            (filtered_by_d1, ['D1_consensus_SH', 'D1_taxon',
             'Original_D1_eligible_reads', 'Excluded_chimeric_conflicts',
             'Adjusted_D1_eligible_reads', 'Matched_D3_reads',
             'Unmatched_D3_reads', 'Nonchimeric_mismatched_D3_reads',
             'Mismatch_rate_pct', 'Pct_nonchimeric_mismatches',
             'Barcodes_with_D1_SH', 'Distinct_alternative_D3_SH']),
        'SINTAX080_nonchimeric_mismatches_by_D3_raw_SH.tsv':
            (filtered_by_raw, ['D3_raw_read_SH', 'D3_taxon',
             'Original_D3_assigned_reads', 'Excluded_chimeric_conflicts',
             'Adjusted_D3_assigned_reads', 'Nonchimeric_mismatched_D3_reads',
             'Mismatch_rate_pct', 'Pct_nonchimeric_mismatches']),
        'SINTAX080_nonchimeric_mismatches_by_barcode.tsv':
            (filtered_by_barcode, ['Barcode', 'All_D3_reads',
             'Original_D1_eligible_reads', 'Excluded_chimeric_conflicts',
             'Adjusted_D1_eligible_reads', 'Nonchimeric_mismatched_reads',
             'Mismatch_rate_pct']),
        'SINTAX080_excluded_chimeric_reference_conflicts.tsv':
            (filtered_exclusions, ['D1_consensus_SH', 'D3_raw_read_SH',
             'Excluded_mismatched_reads', 'Pct_all_original_mismatches',
             'Barcodes_with_pair']),
        'SINTAX080_nonchimeric_confusion_audit.tsv':
            (filtered_audit, ['Metric', 'Value']),
    }
    for filename, (rows, columns) in filtered_outputs.items():
        write_tsv(excluded_dir / filename, rows, columns)

    print('\n=== CHIMERIC SH EXCLUSION SENSITIVITY ANALYSIS ===')
    print(f'  Excluded SH: {excluded_sh}')
    for row in filtered_audit:
        print(f"  {row['Metric']}: {row['Value']}")
    print('\nTop 15 nonchimeric directional conflicts:')
    print('Rank\tD1 consensus SH\tD3 raw SH\tN\t% retained mismatches\tBarcodes')
    for row in filtered_direction[:15]:
        print(f"{row['Rank']}\t{row['D1_consensus_SH']}\t{row['D3_raw_read_SH']}\t"
              f"{row['Mismatched_reads']:,}\t{row['Pct_nonchimeric_mismatches']:.2f}\t"
              f"{row['Barcodes_with_pair']}")
    print('\nFiltered outputs: ' + str(excluded_dir))

    print("\nNOTE: This script audits within-SINTAX D1 versus D3 conflicts.")
    print("The separate SH-matching versus SINTAX contingency is recalculated by script 19.")

if __name__ == '__main__':
    main()
